// Copies the @fontsource woff2 slices the extension needs into
// extension/src/assets/fonts/ and writes fonts.css with relative urls.
// Design 1a uses JetBrains Mono, with M PLUS 1 Code for the Japanese glyphs.
// The numbered slices carry the Japanese glyphs split by unicode-range (the
// Google Fonts slicing), so a page only loads the slices whose characters it shows.
// Usage: node tools/build-fonts.mjs

import { readFile, writeFile, mkdir, copyFile, readdir, rm, stat } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'node_modules', '@fontsource');
const OUT = join(ROOT, 'extension', 'src', 'assets', 'fonts');
const FILES = join(OUT, 'files');

const FAMILIES = [
  { pkg: 'jetbrains-mono', weights: [400, 500, 600, 700], japanese: false },
  { pkg: 'm-plus-1-code', weights: [400, 500, 700], japanese: true },
];

// Japanese slices are named "<pkg>-<n>-<w>-normal"; latin is "<pkg>-latin-<w>-normal".
function wanted(pkg, faceName, japanese) {
  const rest = faceName.slice(pkg.length + 1);
  if (/^latin-\d+-normal$/.test(rest)) return true;
  return japanese && /^\d+-\d+-normal$/.test(rest);
}

const FACE_RE = /\/\* ([^*]+?) \*\/\s*@font-face \{([^}]*)\}/g;

async function main() {
  await rm(OUT, { recursive: true, force: true });
  await mkdir(FILES, { recursive: true });
  const css = ['/* Bundled from @fontsource (SIL Open Font License 1.1). Generated by tools/build-fonts.mjs. */\n'];
  let bytes = 0;
  let count = 0;
  for (const { pkg, weights, japanese } of FAMILIES) {
    for (const w of weights) {
      const src = await readFile(join(SRC, pkg, `${w}.css`), 'utf8');
      for (const m of src.matchAll(FACE_RE)) {
        const name = m[1].replace(/[[\]]/g, '');
        if (!wanted(pkg, name, japanese)) continue;
        const body = m[2];
        const family = /font-family: ([^;]+);/.exec(body)[1];
        const range = /unicode-range: ([^;]+);/.exec(body)?.[1];
        const file = `${name}.woff2`;
        await copyFile(join(SRC, pkg, 'files', file), join(FILES, file));
        bytes += (await stat(join(FILES, file))).size;
        count++;
        css.push(`@font-face{font-family:${family};font-style:normal;font-display:swap;font-weight:${w};`
          + `src:url(./files/${file}) format('woff2');${range ? `unicode-range:${range};` : ''}}`);
      }
    }
  }
  await writeFile(join(OUT, 'fonts.css'), css.join('\n') + '\n');
  for (const { pkg } of FAMILIES) {
    await copyFile(join(SRC, pkg, 'LICENSE'), join(OUT, `LICENSE-${pkg}.txt`));
  }
  const listed = await readdir(FILES);
  console.log(`fonts: ${count} faces, ${listed.length} files, ${(bytes / 1024 / 1024).toFixed(2)} MiB`);
}

main().catch((e) => { console.error(e); process.exit(1); });
