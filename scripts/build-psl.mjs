import { readFile, writeFile } from 'node:fs/promises';
import { domainToASCII } from 'node:url';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const src = process.argv[2];
if (!src) throw new Error('usage: node scripts/build-psl.mjs <public_suffix_list.dat>');
const text = await readFile(src, 'utf8');
const version = (text.match(/^\/\/ VERSION: (.+)$/m) || [])[1] || 'unknown';

const rules = new Set();
for (const raw of text.split('\n')) {
  const line = raw.trim().split(/\s/)[0];
  if (!line || line.startsWith('//')) continue;
  const prefix = line.startsWith('!') ? '!' : line.startsWith('*.') ? '*.' : '';
  const ascii = domainToASCII(line.slice(prefix.length));
  if (!ascii) throw new Error('Cannot convert rule: ' + line);
  rules.add(prefix + ascii);
}

const out = path.join(path.dirname(fileURLToPath(import.meta.url)), '../extension/src/shared/psl-data.js');
await writeFile(out,
  `// Generated by scripts/build-psl.mjs from the Public Suffix List (MPL-2.0, https://publicsuffix.org/).\n`
  + `// PSL VERSION: ${version}. Do not edit by hand.\n`
  + `export const PSL_VERSION = ${JSON.stringify(version)};\n`
  + `export default ${JSON.stringify([...rules].join('\n'))};\n`);
console.log(`psl-data.js: ${rules.size} rules (version ${version})`);
