import { readFile, writeFile, mkdir, copyFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pkg = path.join(ROOT, 'node_modules/jsqr');
const outDir = path.join(ROOT, 'extension/src/third_party');
const { version } = JSON.parse(await readFile(path.join(pkg, 'package.json'), 'utf8'));
const umd = await readFile(path.join(pkg, 'dist/jsQR.js'), 'utf8');

await mkdir(outDir, { recursive: true });
await writeFile(path.join(outDir, 'jsqr.js'),
  `// jsQR ${version} (Apache-2.0, https://github.com/cozmo/jsQR) wrapped as an ES module.\n`
  + `// Generated by scripts/build-jsqr.mjs — do not edit.\n`
  + `const module = { exports: {} };\nconst exports = module.exports;\n`
  + umd
  + `\nconst m = module.exports;\nexport default typeof m === 'function' ? m : m.default;\n`);
await copyFile(path.join(pkg, 'LICENSE'), path.join(outDir, 'jsQR.LICENSE'));
console.log(`third_party/jsqr.js: jsQR ${version}`);
